// Combine all reserved names
export const RESERVED_NAMES = [
  ...MISLEADING_WORDS,
  ...COMPANIES_AND_BRANDS,
]

// Function to check if a name is reserved
export const isReservedName = (name: string): boolean => {
  if (!name) return false
  
  const normalizedName = name.toLowerCase().trim()
  
  // Check exact match only (too restrictive to check for contains)
  if (RESERVED_NAMES.includes(normalizedName)) {
    return true
  }
  
  return false
}

// Function to check if a professional name is valid (not a company/brand)
export const isValidProfessionalName = (fullName: string): boolean => {
  if (!fullName) return false
  
  const normalizedName = fullName.toLowerCase().trim()
  
  // Check if it's a company name pattern (e.g., "Google Haiti", "Digicel Haiti")
  const companyPatterns = [
    /google\s+haiti/i,
    /digicel\s+haiti/i,
    /microsoft\s+corp/i,
    /apple\s+store/i,
    /facebook\s+haiti/i,
    /instagram\s+haiti/i,
    /tiktok\s+haiti/i,
    /natcom\s+haiti/i,
    /haitel\s+haiti/i,
    /access\s+haiti/i,
    /moncash\s+haiti/i,
    /sogebank\s+haiti/i,
    /unibank\s+haiti/i,
    /capital\s+bank\s+haiti/i,
    /republic\s+bank\s+haiti/i,
    /bnc\s+haiti/i,
    /banque\s+nationale\s+de\s+credit\s+haiti/i,
  ]
  
  for (const pattern of companyPatterns) {
    if (pattern.test(normalizedName)) {
      return false
    }
  }
  
  // Check if it contains company/brand name
  for (const company of COMPANIES_AND_BRANDS) {
    if (normalizedName.includes(company)) {
      return false
    }
  }
  
  return true
}
